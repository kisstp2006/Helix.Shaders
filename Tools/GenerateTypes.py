"""Generates the vector types, their swizzles and the component wise math functions of HelixEngine.Shaders."""
import itertools
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent / "Source" / "HelixEngine.Shaders"
COMPONENTS = "xyzw"
KINDS = {"float": "float", "half": "half", "int": "int", "uint": "uint", "bool": "bool"}
HEADER = "// Generated by Tools/GenerateTypes.py.\n\nnamespace HelixEngine.Shaders;\n\n"


def vec(kind, n):
    return f"{kind}{n}"


def args(n, fmt):
    return ", ".join(fmt.format(c=COMPONENTS[i], i=i) for i in range(n))


def vector(kind, n):
    name = vec(kind, n)
    t = KINDS[kind]
    o = [f'[IntrinsicType("{name}")]', f"public struct {name}", "{"]
    o.append("    public " + t + " " + ", ".join(COMPONENTS[:n]) + ";")
    o.append("")
    o.append(f"    public {name}({args(n, t + ' {c}')}) {{ {' '.join(f'this.{c} = {c};' for c in COMPONENTS[:n])} }}")
    o.append(f"    public {name}({t} value) {{ {' '.join(f'{c} = value;' for c in COMPONENTS[:n])} }}")
    if n == 3:
        o.append(f"    public {name}({vec(kind, 2)} xy, {t} z) {{ x = xy.x; y = xy.y; this.z = z; }}")
        o.append(f"    public {name}({t} x, {vec(kind, 2)} yz) {{ this.x = x; y = yz.x; z = yz.y; }}")
    if n == 4:
        o.append(f"    public {name}({vec(kind, 3)} xyz, {t} w) {{ x = xyz.x; y = xyz.y; z = xyz.z; this.w = w; }}")
        o.append(f"    public {name}({t} x, {vec(kind, 3)} yzw) {{ this.x = x; y = yzw.x; z = yzw.y; w = yzw.z; }}")
        o.append(f"    public {name}({vec(kind, 2)} xy, {vec(kind, 2)} zw) {{ x = xy.x; y = xy.y; z = zw.x; w = zw.y; }}")
        o.append(f"    public {name}({vec(kind, 2)} xy, {t} z, {t} w) {{ x = xy.x; y = xy.y; this.z = z; this.w = w; }}")
    o.append("")
    cases = " ".join(f"{i} => {COMPONENTS[i]}," for i in range(n))
    sets = " ".join(f"case {i}: {COMPONENTS[i]} = value; break;" for i in range(n))
    o.append(f"    public {t} this[int index]")
    o.append("    {")
    o.append(f"        readonly get => index switch {{ {cases} _ => throw new System.IndexOutOfRangeException() }};")
    o.append(f"        set {{ switch (index) {{ {sets} default: throw new System.IndexOutOfRangeException(); }} }}")
    o.append("    }")
    o.append("")
    if kind != "bool":
        for op in "+-*/%":
            o.append(f"    public static {name} operator {op}({name} a, {name} b) => new({args(n, 'a.{c} ' + op + ' b.{c}')});")
            o.append(f"    public static {name} operator {op}({name} a, {t} b) => new({args(n, 'a.{c} ' + op + ' b')});")
            o.append(f"    public static {name} operator {op}({t} a, {name} b) => new({args(n, 'a ' + op + ' b.{c}')});")
        if kind != "uint":
            o.append(f"    public static {name} operator -({name} a) => new({args(n, '-a.{c}')});")
        for op in ("<", ">", "<=", ">="):
            o.append(f"    public static bool{n} operator {op}({name} a, {name} b) => new({args(n, 'a.{c} ' + op + ' b.{c}')});")
        if kind not in ("float", "half"):
            for op in "&|^":
                o.append(f"    public static {name} operator {op}({name} a, {name} b) => new({args(n, 'a.{c} ' + op + ' b.{c}')});")
            o.append(f"    public static {name} operator <<({name} a, int b) => new({args(n, 'a.{c} << b')});")
            o.append(f"    public static {name} operator >>({name} a, int b) => new({args(n, 'a.{c} >> b')});")
        for other in ("float", "half", "int", "uint"):
            if other != kind:
                o.append(f"    public static explicit operator {name}({vec(other, n)} v) => new({args(n, '(' + t + ')v.{c}')});")
    else:
        for op in "&|^":
            o.append(f"    public static {name} operator {op}({name} a, {name} b) => new({args(n, 'a.{c} ' + op + ' b.{c}')});")
        o.append(f"    public static {name} operator !({name} a) => new({args(n, '!a.{c}')});")
    o.append(f"    public static bool{n} operator ==({name} a, {name} b) => new({args(n, 'a.{c} == b.{c}')});")
    o.append(f"    public static bool{n} operator !=({name} a, {name} b) => new({args(n, 'a.{c} != b.{c}')});")
    o.append("")
    fmt = ", ".join("{" + c + "}" for c in COMPONENTS[:n])
    o.append(f'    public override readonly string ToString() => $"{name}({fmt})";')
    o.append("")
    for size in (2, 3, 4):
        for combo in itertools.product(COMPONENTS[:n], repeat=size):
            if size == n and "".join(combo) == COMPONENTS[:n]:
                continue
            swizzle = "".join(combo)
            result = vec(kind, size)
            get = f"readonly get => new({', '.join(combo)});"
            if len(set(combo)) == size:
                assign = " ".join(f"{c} = value.{COMPONENTS[i]};" for i, c in enumerate(combo))
                o.append(f"    public {result} {swizzle} {{ {get} set {{ {assign} }} }}")
            else:
                o.append(f"    public readonly {result} {swizzle} => new({', '.join(combo)});")
    o.append("}")
    return "\n".join(o) + "\n"


# name, intrinsic, scalar expression with {a} {b} {c}, argument count
FLOAT_FUNCTIONS = [
    ("Abs", "abs", "System.MathF.Abs({a})", 1),
    ("Sign", "sign", "(float)System.MathF.Sign({a})", 1),
    ("Floor", "floor", "System.MathF.Floor({a})", 1),
    ("Ceil", "ceil", "System.MathF.Ceiling({a})", 1),
    ("Round", "round", "System.MathF.Round({a}, System.MidpointRounding.ToEven)", 1),
    ("Trunc", "trunc", "System.MathF.Truncate({a})", 1),
    ("Frac", "frac", "{a} - System.MathF.Floor({a})", 1),
    ("Sqrt", "sqrt", "System.MathF.Sqrt({a})", 1),
    ("Rsqrt", "rsqrt", "1.0f / System.MathF.Sqrt({a})", 1),
    ("Exp", "exp", "System.MathF.Exp({a})", 1),
    ("Exp2", "exp2", "System.MathF.Pow(2.0f, {a})", 1),
    ("Log", "log", "System.MathF.Log({a})", 1),
    ("Log2", "log2", "System.MathF.Log2({a})", 1),
    ("Sin", "sin", "System.MathF.Sin({a})", 1),
    ("Cos", "cos", "System.MathF.Cos({a})", 1),
    ("Tan", "tan", "System.MathF.Tan({a})", 1),
    ("Asin", "asin", "System.MathF.Asin({a})", 1),
    ("Acos", "acos", "System.MathF.Acos({a})", 1),
    ("Atan", "atan", "System.MathF.Atan({a})", 1),
    ("Saturate", "saturate", "System.Math.Clamp({a}, 0.0f, 1.0f)", 1),
    ("Radians", "radians", "{a} * (System.MathF.PI / 180.0f)", 1),
    ("Degrees", "degrees", "{a} * (180.0f / System.MathF.PI)", 1),
    ("Atan2", "atan2", "System.MathF.Atan2({a}, {b})", 2),
    ("Pow", "pow", "System.MathF.Pow({a}, {b})", 2),
    ("Min", "min", "System.MathF.Min({a}, {b})", 2),
    ("Max", "max", "System.MathF.Max({a}, {b})", 2),
    ("Step", "step", "({b} >= {a} ? 1.0f : 0.0f)", 2),
    ("Fmod", "fmod", "{a} % {b}", 2),
    ("Clamp", "clamp", "System.MathF.Min(System.MathF.Max({a}, {b}), {c})", 3),
    ("Lerp", "lerp", "{a} + ({b} - {a}) * {c}", 3),
    ("Smoothstep", "smoothstep", "SmoothstepScalar({a}, {b}, {c})", 3),
]
INT_FUNCTIONS = [
    ("Abs", "abs", "System.Math.Abs({a})", 1, ("int",)),
    ("Min", "min", "System.Math.Min({a}, {b})", 2, ("int", "uint")),
    ("Max", "max", "System.Math.Max({a}, {b})", 2, ("int", "uint")),
    ("Clamp", "clamp", "System.Math.Min(System.Math.Max({a}, {b}), {c})", 3, ("int", "uint")),
]


def function(name, intrinsic, expr, count, kind, n):
    t = KINDS[kind] if n == 1 else vec(kind, n)
    params = ", ".join(f"{t} {p}" for p in "abc"[:count])
    if n == 1:
        body = expr.format(a="a", b="b", c="c")
    else:
        body = "new(" + ", ".join(expr.format(a=f"a.{c}", b=f"b.{c}", c=f"c.{c}") for c in COMPONENTS[:n]) + ")"
    return f'    [Intrinsic("{intrinsic}")] public static {t} {name}({params}) => {body};'


def math():
    o = [HEADER.rstrip("\n"), "", "public static partial class ShaderMath", "{"]
    for name, intrinsic, expr, count in FLOAT_FUNCTIONS:
        for n in (1, 2, 3, 4):
            o.append(function(name, intrinsic, expr, count, "float", n))
        if name in ("Min", "Max", "Pow", "Fmod"):
            for n in (2, 3, 4):
                v = vec("float", n)
                body = "new(" + ", ".join(expr.format(a=f"a.{c}", b="b") for c in COMPONENTS[:n]) + ")"
                o.append(f'    [Intrinsic("{intrinsic}")] public static {v} {name}({v} a, float b) => {body};')
        if name in ("Clamp", "Lerp"):
            for n in (2, 3, 4):
                v = vec("float", n)
                if name == "Lerp":
                    body = "new(" + ", ".join(expr.format(a=f"a.{c}", b=f"b.{c}", c="c") for c in COMPONENTS[:n]) + ")"
                    o.append(f'    [Intrinsic("{intrinsic}")] public static {v} {name}({v} a, {v} b, float c) => {body};')
                else:
                    body = "new(" + ", ".join(expr.format(a=f"a.{c}", b="b", c="c") for c in COMPONENTS[:n]) + ")"
                    o.append(f'    [Intrinsic("{intrinsic}")] public static {v} {name}({v} a, float b, float c) => {body};')
        o.append("")
    for name, intrinsic, expr, count, kinds in INT_FUNCTIONS:
        for kind in kinds:
            for n in (1, 2, 3, 4):
                o.append(function(name, intrinsic, expr, count, kind, n))
        o.append("")
    for n in (2, 3, 4):
        v = vec("float", n)
        dot = " + ".join(f"a.{c} * b.{c}" for c in COMPONENTS[:n])
        o.append(f'    [Intrinsic("dot")] public static float Dot({v} a, {v} b) => {dot};')
        o.append(f'    [Intrinsic("length")] public static float Length({v} a) => System.MathF.Sqrt(Dot(a, a));')
        o.append(f'    [Intrinsic("distance")] public static float Distance({v} a, {v} b) => Length(a - b);')
        o.append(f'    [Intrinsic("normalize")] public static {v} Normalize({v} a) => a * (1.0f / Length(a));')
        o.append(f'    [Intrinsic("reflect")] public static {v} Reflect({v} incident, {v} normal) => incident - 2.0f * Dot(normal, incident) * normal;')
        o.append(f'    [Intrinsic("ddx")] public static {v} Ddx({v} a) => default;')
        o.append(f'    [Intrinsic("ddy")] public static {v} Ddy({v} a) => default;')
        o.append(f'    [Intrinsic("fwidth")] public static {v} Fwidth({v} a) => default;')
        for kind in ("float", "int", "uint", "bool"):
            k = vec(kind, n)
            pick = ", ".join(f"mask.{c} ? a.{c} : b.{c}" for c in COMPONENTS[:n])
            o.append(f'    [Intrinsic("select")] public static {k} Select(bool{n} mask, {k} a, {k} b) => new({pick});')
        o.append(f'    [Intrinsic("any")] public static bool Any(bool{n} a) => {" || ".join(f"a.{c}" for c in COMPONENTS[:n])};')
        o.append(f'    [Intrinsic("all")] public static bool All(bool{n} a) => {" && ".join(f"a.{c}" for c in COMPONENTS[:n])};')
        o.append("")
    o.append("}")
    return "\n".join(o) + "\n"


def main():
    for kind in KINDS:
        text = HEADER + "\n".join(vector(kind, n) for n in (2, 3, 4))
        (ROOT / "Types" / "Generated" / f"{kind.capitalize()}Vectors.g.cs").write_text(text, encoding="ascii", newline="\n")
    (ROOT / "Math" / "Generated" / "ShaderMath.g.cs").write_text(math(), encoding="ascii", newline="\n")


if __name__ == "__main__":
    main()
